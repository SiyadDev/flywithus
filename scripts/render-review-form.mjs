// Builds .github/ISSUE_TEMPLATE/update-reviews.yml from src/data/reviews.json so the
// form always shows the numbers currently on the website.
// Run after changing reviews.json:  npm run reviews:form
// (The GitHub workflows run this automatically.)

import fs from 'node:fs';

const d = JSON.parse(fs.readFileSync('src/data/reviews.json', 'utf8'));
const b = d.breakdown;
const google = 'https://www.google.com/search?q=FLY+WITH+US+TOURS+%26+TRAVELS+Mannarkkad+reviews';

const field = (id, label, now, extra = '') => `  - type: input
    id: ${id}
    attributes:
      label: ${label}
      description: '${extra}Website now: ${now}'
      placeholder: Leave empty = no change`;

const yml = `# GENERATED by scripts/render-review-form.mjs from src/data/reviews.json. Do not edit by hand.
name: Update Google reviews
description: Type the numbers that changed on Google. The website updates itself.
title: Update Google reviews
labels: [review-update]
body:
  - type: markdown
    attributes:
      value: |
        ### On the website now
        **${d.rating}★** from **${d.count} reviews** · 5★ ${b.five} · 4★ ${b.four} · 3★ ${b.three} · 2★ ${b.two} · 1★ ${b.one}
        <sub>Last updated ${d.updatedAt}</sub>

        Compare with our **[Google reviews](${google})**.

        **Only fill in the numbers that changed. Leave a box empty to keep the website's current number.**
        Example: 2 new five-star reviews → total **${d.count + 2}**, 5★ **${b.five + 2}**, leave the rest empty.
${field('rating', 'Google rating', d.rating, 'The number next to the stars. ')}
${field('count', 'Total number of reviews', d.count)}
${field('five', '5★ reviews', b.five)}
${field('four', '4★ reviews', b.four)}
${field('three', '3★ reviews', b.three)}
${field('two', '2★ reviews', b.two)}
${field('one', '1★ reviews', b.one)}
`;

const out = '.github/ISSUE_TEMPLATE/update-reviews.yml';
const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (before === yml) console.log('Form already shows the current numbers.');
else {
  fs.writeFileSync(out, yml);
  console.log(`Form updated: ${d.rating}★, ${d.count} reviews.`);
}
